#!/usr/bin/env python3
"""Generate additional Realtime contexts on the PBX host and reload dialplan only."""
import argparse
from pathlib import Path
import re
import subprocess
import tempfile
import os

ROOT = Path(__file__).resolve().parents[2]
CONFIG = ROOT / 'asterisk/config'
TARGET = CONFIG / 'realtime-contexts.conf'


def command(arguments, body=None):
    result = subprocess.run(arguments, input=body, capture_output=True, text=True, cwd=ROOT)
    if result.returncode:
        raise RuntimeError('PBX command failed; sensitive connection output withheld.')
    return result.stdout


def replace(content):
    with tempfile.NamedTemporaryFile(mode='w', dir=CONFIG, prefix='.contexts-', delete=False) as handle:
        handle.write(content)
        temporary = Path(handle.name)
    os.chmod(temporary, 0o644)
    os.replace(temporary, TARGET)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Report whether regeneration is needed without changes')
    options = parser.parse_args()
    query = '''BEGIN READ ONLY;
SELECT context FROM ps_endpoints WHERE context IS NOT NULL AND context <> ''
UNION SELECT context FROM extensions ORDER BY context;
ROLLBACK;
'''
    output = command(['docker', 'compose', 'exec', '-T', 'postgres', 'sh', '-c',
                      'psql -X -qAt -U "$POSTGRES_USER" -d "$POSTGRES_DB" -v ON_ERROR_STOP=1'], query)
    contexts = sorted(set(output.splitlines()))
    if any(not re.fullmatch(r'[a-z][a-z0-9-]{0,39}', context) for context in contexts):
        raise RuntimeError('An unsupported context name was found; configuration was not changed.')
    if set(contexts) & {'general', 'globals'}:
        raise RuntimeError('A reserved context name was found; configuration was not changed.')
    static = set(re.findall(r'^\[([a-z][a-z0-9-]*)\]', (CONFIG / 'extensions.conf').read_text(), re.M))
    additional = [context for context in contexts if context not in static]
    desired = '; Generated by asterisk/scripts/sync-realtime-contexts.py.\n'
    desired += ''.join(f'\n[{context}]\nswitch => Realtime/{context}@extensions\n' for context in additional)
    previous = TARGET.read_text() if TARGET.exists() else None
    if previous == desired:
        print('Realtime contexts are up to date.')
        return 0
    if options.check:
        print('Realtime context regeneration is needed.')
        return 1
    replace(desired)
    try:
        output = command(['docker', 'compose', 'exec', '-T', 'asterisk', 'asterisk', '-rx', 'dialplan reload'])
        if 'Dialplan reloaded' not in output:
            raise RuntimeError('Dialplan reload was not acknowledged.')
    except Exception:
        if previous is None:
            replace('; Context synchronization failed; previous static contexts retained.\n')
        else:
            replace(previous)
        command(['docker', 'compose', 'exec', '-T', 'asterisk', 'asterisk', '-rx', 'dialplan reload'])
        raise
    print(f'Synchronized {len(additional)} additional contexts; dialplan reloaded. No SIP reload was performed.')
    return 0


if __name__ == '__main__':
    try:
        raise SystemExit(main())
    except RuntimeError as error:
        raise SystemExit(str(error))
